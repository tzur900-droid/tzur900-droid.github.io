NUMBERS = {
    "א": "אחד", "ב": "שנים", "ג": "שלשה", "ד": "ארבעה", "ה": "חמשה", "ו": "ששה", "ז": "שבעה", "ח": "שמונה",
    "ט": "תשעה", "י": "עשרה", "יא": "אחד עשר", "יב": "שנים עשר", "יג": "שלשה עשר", "יד": "ארבעה עשר",
    "טו": "חמשה עשר", "טז": "ששה עשר", "יז": "שבעה עשר", "יח": "שמונה עשר", "יט": "תשעה עשר", "כ": "עשרים",
    "כא": "עשרים ואחד", "כד": "עשרים וארבעה", "ל": "שלשים", "מ": "ארבעים", "נ": "חמשים", "ק": "מאה",
}


def _table():
    out = {}
    for line in ABBREV.strip().split("\n"):
        k, v = line.split("=", 1)
        out[k.replace("״", '"')] = v.split("|")[0].split()
    return out


TABLE = _table()
PREFIX = "ודהבלמשכ"


def expand(word):
    """The words an abbreviated word stands for, or None. A prefix (ו, ד, ה, ב, ל, מ, ש, כ)
    stays on the first word."""
    w = word.strip(".,:;()[]").replace("״", '"').replace("''", '"').replace("׳", "'")
    if '"' not in w and not w.endswith("'"):
        return None
    for k in range(0, 3):
        pre, rest = w[:k], w[k:]
        if any(c not in PREFIX for c in pre):
            break
        bare = rest.replace('"', "").replace("'", "")
        number = '"' in rest and bare in NUMBERS
        # after ב, מ or ל a number before anything else: בי"א is "on the eleventh", not
        # "on some say"
        if rest in TABLE and not (number and pre and pre[-1] in "במל"):
            words = list(TABLE[rest])
            words[0] = pre + words[0]
            return words
        if number:
            words = NUMBERS[bare].split()
            words[0] = pre + words[0]
            return words
    return None
